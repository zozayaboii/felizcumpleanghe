function renderizarParrafos(contenedor, texto) {
  contenedor.innerHTML = "";
  texto.split("\n\n").forEach((bloque) => {
    const p = document.createElement("p");
    p.textContent = bloque.trim();
    contenedor.appendChild(p);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.getElementById("subtitulo-hero").textContent = CONTENIDO.subtituloHero;
  document.getElementById("titulo-hero").textContent = CONTENIDO.tituloHero;
  renderizarParrafos(document.getElementById("carta-principal"), CONTENIDO.cartaPrincipal);

  const grid = document.getElementById("sobres-grid");
  const modal = document.getElementById("modal");

  CONTENIDO.cartas.forEach((carta) => {
    const btn = document.createElement("button");
    btn.className = "sobre";
    btn.innerHTML = `
      <span class="sobre-pliegues" aria-hidden="true"></span>
      <span class="sobre-solapa" aria-hidden="true"></span>
      <span class="sello-lacre">${carta.numero}</span>
      <strong>${carta.titulo}</strong>
    `;
    btn.addEventListener("click", () => {
      btn.classList.add("abierto");
      document.getElementById("modal-etiqueta").textContent = carta.etiqueta;
      document.getElementById("modal-titulo").textContent = carta.titulo;
      renderizarParrafos(document.getElementById("modal-texto"), carta.texto);
      modal.classList.add("activo");
    });
    grid.appendChild(btn);
  });

  document.getElementById("cerrar-modal").addEventListener("click", () => {
    modal.classList.remove("activo");
  });

  modal.addEventListener("click", (e) => {
    if (e.target === modal) modal.classList.remove("activo");
  });

  // Mini bloc de dibujo
  const canvas = document.getElementById("lienzo-dibujo");
  if (canvas) {
    const ctx = canvas.getContext("2d");
    let dibujando = false;
    let colorActual = "#1b1e2e";
    let grosorActual = 4;

    function iniciarPapel() {
      canvas.width = canvas.clientWidth || 320;
      canvas.height = 270;
      ctx.fillStyle = "#f4eadc";
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      ctx.lineCap = "round";
      ctx.lineJoin = "round";
    }

    iniciarPapel();

    function obtenerPosicion(e) {
      const rect = canvas.getBoundingClientRect();
      return {
        x: e.clientX - rect.left,
        y: e.clientY - rect.top
      };
    }

    canvas.addEventListener("pointerdown", (e) => {
      dibujando = true;
      const pos = obtenerPosicion(e);
      ctx.beginPath();
      ctx.moveTo(pos.x, pos.y);
    });

    canvas.addEventListener("pointermove", (e) => {
      if (!dibujando) return;
      const pos = obtenerPosicion(e);
      ctx.strokeStyle = colorActual;
      ctx.lineWidth = grosorActual;
      ctx.lineTo(pos.x, pos.y);
      ctx.stroke();
    });

    const detenerTrazo = () => { dibujando = false; };
    canvas.addEventListener("pointerup", detenerTrazo);
    canvas.addEventListener("pointerleave", detenerTrazo);

    const botonesColor = document.querySelectorAll(".color-btn");
    const btnGoma = document.getElementById("btn-goma");

    botonesColor.forEach((btn) => {
      btn.addEventListener("click", () => {
        botonesColor.forEach((b) => b.classList.remove("activo"));
        btnGoma.classList.remove("activo");
        btn.classList.add("activo");
        colorActual = btn.dataset.color;
        grosorActual = 4;
      });
    });

    btnGoma.addEventListener("click", () => {
      botonesColor.forEach((b) => b.classList.remove("activo"));
      btnGoma.classList.add("activo");
      colorActual = "#f4eadc";
      grosorActual = 18;
    });

    document.getElementById("btn-limpiar").addEventListener("click", iniciarPapel);

    document.getElementById("btn-descargar").addEventListener("click", () => {
      const enlace = document.createElement("a");
      enlace.download = "dibujo-anghe.png";
      enlace.href = canvas.toDataURL("image/png");
      enlace.click();
    });
  }

  // Efecto festivo de corazones y formas
  const festejoCanvas = document.getElementById("lienzo-festejo");
  if (festejoCanvas) {
    const fCtx = festejoCanvas.getContext("2d");
    const colores = ["#f48fb1", "#6ec6ff", "#69d2a0", "#f4eadc"];
    let particulas = [];
    let animando = false;

    function lanzarFestejo() {
      festejoCanvas.width = window.innerWidth;
      festejoCanvas.height = window.innerHeight;

      for (let i = 0; i < 60; i++) {
        particulas.push({
          x: Math.random() * festejoCanvas.width,
          y: -20 - Math.random() * 260,
          velY: 2.2 + Math.random() * 2.8,
          oscilacion: Math.random() * Math.PI * 2,
          rotacion: Math.random() * Math.PI,
          velRot: (Math.random() - 0.5) * 0.08,
          color: colores[i % colores.length],
          tipo: i % 3
        });
      }

      if (!animando) {
        animando = true;
        animarFestejo();
      }
    }

    function dibujarCorazon(ctx, color) {
      ctx.fillStyle = color;
      ctx.beginPath();
      ctx.moveTo(0, 3);
      ctx.bezierCurveTo(0, -2, -7, -2, -7, 3);
      ctx.bezierCurveTo(-7, 7, 0, 10, 0, 13);
      ctx.bezierCurveTo(0, 10, 7, 7, 7, 3);
      ctx.bezierCurveTo(7, -2, 0, -2, 0, 3);
      ctx.fill();
    }

    function animarFestejo() {
      fCtx.clearRect(0, 0, festejoCanvas.width, festejoCanvas.height);

      particulas.forEach((p) => {
        p.y += p.velY;
        p.oscilacion += 0.04;
        p.x += Math.sin(p.oscilacion) * 1.1;
        p.rotacion += p.velRot;

        fCtx.save();
        fCtx.translate(p.x, p.y);
        fCtx.rotate(p.rotacion);

        if (p.tipo === 0) {
          dibujarCorazon(fCtx, p.color);
        } else if (p.tipo === 1) {
          fCtx.fillStyle = p.color;
          fCtx.fillRect(-4, -4, 8, 8);
        } else {
          fCtx.fillStyle = p.color;
          fCtx.beginPath();
          fCtx.arc(0, 0, 4, 0, Math.PI * 2);
          fCtx.fill();
        }
        fCtx.restore();
      });

      particulas = particulas.filter((p) => p.y < festejoCanvas.height + 30);

      if (particulas.length > 0) {
        requestAnimationFrame(animarFestejo);
      } else {
        animando = false;
      }
    }

    lanzarFestejo();
    document.getElementById("btn-festejo").addEventListener("click", lanzarFestejo);
  }
});
